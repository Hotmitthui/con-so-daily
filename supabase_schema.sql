-- 1. BẢNG: ve_truyen_thong (Lưu kho vé, ảnh vé)
create table ve_truyen_thong (
  ngay_so date primary key, -- Ngày xổ (Khóa chính)
  anh_ve_url text,          -- Link ảnh vé
  chi_tiet_ve jsonb default '{}'::jsonb, -- Kho vé: {"00": 5, "01": 2}
  so_hang int default 5,    -- Số hàng để vẽ lưới Grid trên ảnh
  trang_thai_khoa boolean default false, -- Trạng thái khóa bán Offline
  allow_prebooking boolean default false, -- Cho phép đặt vé ngày tiếp theo
  created_at timestamptz default now()
);

-- 2. BẢNG: don_hang (Lưu đơn khách đặt)
create table don_hang (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  ngay_so date,
  ho_ten text,
  sdt text,
  danh_sach_so jsonb, -- Vé khách đặt: {"52": 2, "79": 1}
  trang_thai text default 'moi' -- Trạng thái đơn: moi, da_xac_nhan...
);

