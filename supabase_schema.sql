-- Hàm 1: Bật/Tắt khóa hệ thống (Chỉ chạy khi đúng mật khẩu)
-- Hacker không thể thấy mật khẩu vì nó nằm trong database
CREATE OR REPLACE FUNCTION admin_toggle_lock(
  p_ngay_so text, 
  p_password text
) RETURNS boolean AS $$
DECLARE
  v_current_state boolean;
BEGIN
  IF p_password = '113355' THEN -- MẬT KHẨU ADMIN NẰM Ở ĐÂY
    -- Lấy trạng thái hiện tại
    SELECT trang_thai_khoa INTO v_current_state 
    FROM ve_truyen_thong 
    WHERE ngay_so::text = p_ngay_so;
    
    IF NOT FOUND THEN
      INSERT INTO ve_truyen_thong (ngay_so, trang_thai_khoa) VALUES (p_ngay_so::date, true);
      RETURN true;
    END IF;

    -- Đảo ngược trạng thái
    UPDATE ve_truyen_thong
    SET trang_thai_khoa = NOT COALESCE(v_current_state, false)
    WHERE ngay_so::text = p_ngay_so;
    
    RETURN true;
  ELSE
    RAISE EXCEPTION 'Mật khẩu không đúng!';
  END IF;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Hàm 1b: Bật/Tắt cho phép đặt vé ngày tiếp theo
CREATE OR REPLACE FUNCTION admin_set_prebooking(
  p_ngay_so text,
  p_enabled boolean,
  p_password text
) RETURNS boolean AS $$
BEGIN
  IF p_password = '113355' THEN
    -- Tắt tất cả ngày đang được phép trước
    UPDATE ve_truyen_thong
    SET allow_prebooking = false
    WHERE allow_prebooking = true;

    -- Nếu bật -> bật đúng ngày được chọn
    IF p_enabled THEN
      UPDATE ve_truyen_thong
      SET allow_prebooking = true
      WHERE ngay_so::text = p_ngay_so;
    END IF;

    RETURN true;
  ELSE
    RAISE EXCEPTION 'Mật khẩu không đúng!';
  END IF;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Hàm 2: Đặt vé an toàn (Transaction + Antibot Check)
-- Tích hợp kiểm tra User-Agent để chống tool tự động (curl, postman, python...)
CREATE OR REPLACE FUNCTION dat_ve_truyen_thong(
  p_ngay_so text,
  p_ho_ten text,
  p_sdt text,
  p_danh_sach_so jsonb,
  p_ref_id text DEFAULT NULL
) RETURNS boolean AS $$
DECLARE
  v_initial_stock jsonb;
  v_key text; v_val text;
  v_requested_qty int; v_initial_qty int; v_sold_qty int;
  v_headers json;
  v_user_agent text;
BEGIN
  -- Lấy thông tin User-Agent từ request người dùng gửi tới
  BEGIN
    v_headers := current_setting('request.headers', true)::json;
    v_user_agent := v_headers->>'user-agent';
  EXCEPTION WHEN OTHERS THEN
    v_user_agent := NULL;
  END;

  -- CHẶN 100% các công cụ tự động dòng lệnh (curl, postman, python...)
  IF v_user_agent IS NULL 
     OR v_user_agent ILIKE '%curl%' 
     OR v_user_agent ILIKE '%postman%' 
     OR v_user_agent ILIKE '%python%' 
     OR v_user_agent ILIKE '%insomnia%' THEN
    RAISE EXCEPTION 'Yêu cầu bị từ chối! Không chấp nhận công cụ tự động.';
  END IF;

  SELECT chi_tiet_ve INTO v_initial_stock FROM ve_truyen_thong WHERE ngay_so::text = p_ngay_so;
  IF v_initial_stock IS NULL THEN RAISE EXCEPTION 'Chưa có dữ liệu vé cho ngày này'; END IF;

  FOR v_key, v_val IN SELECT * FROM jsonb_each_text(p_danh_sach_so) LOOP
    v_requested_qty := v_val::int;
    v_initial_qty := COALESCE((v_initial_stock->>v_key)::int, 0);
    SELECT COALESCE(SUM((danh_sach_so->>v_key)::int), 0) INTO v_sold_qty FROM don_hang WHERE ngay_so::text = p_ngay_so;
    IF (v_initial_qty - v_sold_qty) < v_requested_qty THEN RAISE EXCEPTION 'Số % hiện không đủ vé', v_key; END IF;
  END LOOP;

  INSERT INTO don_hang (ngay_so, ho_ten, sdt, danh_sach_so, trang_thai, ref_id)
  VALUES (p_ngay_so::date, p_ho_ten, p_sdt, p_danh_sach_so, 'moi', p_ref_id);

  RETURN true;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

