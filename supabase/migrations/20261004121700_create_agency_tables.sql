create table if not exists public.dai_ly (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique
    check (slug = lower(slug) and slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  ten_dai_ly text not null,
  auth_user_id uuid unique references auth.users(id) on delete restrict,
  trang_thai text not null default 'cho_duyet'
    check (trang_thai in ('cho_duyet', 'hoat_dong', 'tam_khoa')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.ve_truyen_thong_dly (
  dai_ly_id uuid not null references public.dai_ly(id) on delete restrict,
  ngay_so date not null,
  chi_tiet_ve jsonb not null default '{}'::jsonb,
  ve_dien_tu jsonb not null default '{}'::jsonb,
  so_hang integer not null default 5 check (so_hang > 0),
  trang_thai_khoa boolean not null default false,
  allow_prebooking boolean not null default false,
  created_at timestamptz not null default now(),
  primary key (dai_ly_id, ngay_so)
);

create table if not exists public.don_hang_dly (
  id bigint generated by default as identity primary key,
  dai_ly_id uuid not null references public.dai_ly(id) on delete restrict,
  created_at timestamptz not null default now(),
  ngay_so date not null,
  ho_ten text not null,
  sdt text not null,
  danh_sach_so jsonb not null,
  trang_thai text not null default 'moi',
  ref_id text
);

create index if not exists don_hang_dly_agency_date_created_idx
  on public.don_hang_dly (dai_ly_id, ngay_so, created_at desc);

create index if not exists don_hang_dly_agency_created_idx
  on public.don_hang_dly (dai_ly_id, created_at desc);

alter table public.dai_ly enable row level security;
alter table public.ve_truyen_thong_dly enable row level security;
alter table public.don_hang_dly enable row level security;

grant select, insert, update, delete
  on public.dai_ly, public.ve_truyen_thong_dly, public.don_hang_dly
  to authenticated;

grant all privileges
  on public.dai_ly, public.ve_truyen_thong_dly, public.don_hang_dly
  to service_role;
